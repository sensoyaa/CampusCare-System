import { serve } from "https://deno.land/std@0.168.0/http/server.ts";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers":
    "authorization, x-client-info, apikey, content-type, x-supabase-client-platform, x-supabase-client-platform-version, x-supabase-client-runtime, x-supabase-client-runtime-version",
};

serve(async (req) => {
  if (req.method === "OPTIONS") {
    return new Response(null, { headers: corsHeaders });
  }

  try {
    const { messages } = await req.json();
    const LOVABLE_API_KEY = Deno.env.get("LOVABLE_API_KEY");
    if (!LOVABLE_API_KEY) throw new Error("LOVABLE_API_KEY is not configured");

    const response = await fetch("https://ai.gateway.lovable.dev/v1/chat/completions", {
      method: "POST",
      headers: {
        Authorization: `Bearer ${LOVABLE_API_KEY}`,
        "Content-Type": "application/json",
      },
      body: JSON.stringify({
        model: "google/gemini-3-flash-preview",
        messages: [
          {
            role: "system",
            content: `You are CampusCare AI, a compassionate and knowledgeable mental wellness assistant for Bukidnon State University (BukSU) students and staff. Your role is to:

1. Provide empathetic mental health support and practical coping strategies
2. Guide users to campus resources like counseling appointments, Brown Bag Sessions, and events
3. Help with stress, anxiety, depression, sleep issues, loneliness, and academic pressure
4. Recommend the Mental Health Self-Assessment test when appropriate
5. Encourage professional help when needed — remind users they can book counselor appointments through the app
6. Be warm, supportive, and non-judgmental in all responses

Important guidelines:
- Never diagnose mental health conditions — you are a support companion, not a clinician
- If someone expresses suicidal thoughts or severe crisis, urge them to contact emergency services immediately
- Keep responses concise but helpful (2-4 paragraphs max)
- Use emojis sparingly to keep a friendly tone
- You can reference CampusCare app features: Book Appointment, Mental Health Test, Brown Bag Sessions, Events, Schedule
- Always remind users that counseling is free and confidential for all BukSU students`,
          },
          ...messages,
        ],
        stream: true,
      }),
    });

    if (!response.ok) {
      if (response.status === 429) {
        return new Response(JSON.stringify({ error: "Rate limit exceeded. Please try again in a moment." }), {
          status: 429,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      if (response.status === 402) {
        return new Response(JSON.stringify({ error: "AI credits exhausted. Please contact support." }), {
          status: 402,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        });
      }
      const text = await response.text();
      console.error("AI gateway error:", response.status, text);
      return new Response(JSON.stringify({ error: "AI service unavailable" }), {
        status: 500,
        headers: { ...corsHeaders, "Content-Type": "application/json" },
      });
    }

    return new Response(response.body, {
      headers: { ...corsHeaders, "Content-Type": "text/event-stream" },
    });
  } catch (e) {
    console.error("chat error:", e);
    return new Response(JSON.stringify({ error: e instanceof Error ? e.message : "Unknown error" }), {
      status: 500,
      headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  }
});
